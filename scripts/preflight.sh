#!/usr/bin/env bash
# Hardware + OS preflight for an OQVIAN deployment.
# Prints a report and writes hardware.env with recommended Ollama settings.
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/hardware.env"

cpu=$(awk -F': ' '/model name/{print $2; exit}' /proc/cpuinfo 2>/dev/null || echo unknown)
cores=$(nproc 2>/dev/null || echo '?')
mem_gb=$(awk '/MemTotal/{printf "%.1f", $2/1048576}' /proc/meminfo 2>/dev/null || echo '?')
disk_gb=$(df -BG --output=avail "$ROOT" 2>/dev/null | tail -1 | tr -dc '0-9')
distro=$( (. /etc/os-release 2>/dev/null && echo "$PRETTY_NAME") || echo unknown )

vram_mb=0
gpu_kind="none"
gpu_name=""

if command -v nvidia-smi >/dev/null 2>&1; then
  read -r gpu_name vram_mb < <(nvidia-smi --query-gpu=name,memory.total \
      --format=csv,noheader,nounits 2>/dev/null | head -1 | awk -F', ' '{print $1" "$2}')
  [ "${vram_mb:-0}" -gt 0 ] 2>/dev/null && gpu_kind="nvidia"
fi

if [ "$gpu_kind" = "none" ] && command -v lspci >/dev/null 2>&1; then
  line=$(lspci 2>/dev/null | grep -iE 'vga|3d controller|display' | head -1)
  gpu_name=${line#*: }
  case "$line" in
    *NVIDIA*) gpu_kind="nvidia" ;;
    *Intel*)  gpu_kind="intel" ;;
    *AMD*|*Radeon*) gpu_kind="amd" ;;
  esac
fi

# VRAM heuristic when only lspci is available
if [ "$vram_mb" -eq 0 ] && [ "$gpu_kind" = "intel" ]; then vram_mb=4096; fi
if [ "$vram_mb" -eq 0 ] && [ "$gpu_kind" = "amd" ]; then vram_mb=4096; fi

if [ "$vram_mb" -ge 12000 ]; then
  ctx=32768; note="comfortable: 14B/32B possible"
elif [ "$vram_mb" -ge 6000 ]; then
  ctx=32768; note="good: 7B fully offloaded, 14B partially"
elif [ "$vram_mb" -ge 3000 ]; then
  ctx=16384; note="7B mostly offloaded — the target profile"
else
  ctx=8192;  note="CPU-only: keep context small, expect slow turns"
fi

case "$gpu_kind" in
  nvidia) gpu_env="OLLAMA_NUM_GPU=999" ;;
  intel)  gpu_env="OLLAMA_VULKAN=1" ;;
  amd)    gpu_env="OLLAMA_NUM_GPU=999" ;;
  *)      gpu_env="" ;;
esac

cat <<EOF
== OQVIAN preflight ==
distro     $distro
cpu        $cpu ($cores threads)
memory     ${mem_gb} GB
disk free  ${disk_gb:-?} GB
gpu        ${gpu_name:-none detected} (${gpu_kind}, ${vram_mb} MB VRAM)
profile    ${note}
context    ${ctx}
gpu env    ${gpu_env:-none}

expected 7B Q4 performance
  CPU only            1-3 tok/s       (this is too slow for agent loops)
  iGPU / Vulkan       8-15 tok/s
  4 GB dGPU offload   12-25 tok/s
  8 GB+ dGPU          25-45 tok/s
EOF

{
  echo "# generated by preflight.sh — sourced by the ollama service"
  echo "OQVIAN_NUM_CTX=$ctx"
  echo "OQVIAN_VRAM_MB=$vram_mb"
  echo "OQVIAN_GPU_KIND=$gpu_kind"
  [ -n "$gpu_env" ] && echo "$gpu_env"
} > "$OUT"

echo
echo "wrote $OUT"
